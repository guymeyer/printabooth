import Module from "manifold-3d"; import * as g from "../app/geom.js"; import { packBeds, projectFiles, PRINTERS } from "../app/pack3mf.js";
import fs from "fs";
const E = g.makeEngine(await Module());
const [,, fit = "universal", orient = "landscape", out = "/tmp/claude-0/sp/ps/t.3mf", mods = "1"] = process.argv;
const c = structuredClone(g.DEFAULTS); c.fitMode = fit; c.orientation = orient; if (orient === "portrait") c.camSide = "right";
const part = process.argv[6] || "frame"; const r = E.exportSTL(part, c); if (mods === "0") r.mods = [];
console.log("mods", r.mods.map((b) => `${b.label} ${b.angle} x${b.min[0].toFixed(0)}..${b.max[0].toFixed(0)} y${b.min[1].toFixed(0)}..${b.max[1].toFixed(0)} z${b.min[2].toFixed(1)}..${b.max[2].toFixed(1)}`));
const items = [{ name: part, fixed: true, objName: part, label: part, w: r.size[0], h: r.size[1] }];
const beds = packBeds(items, PRINTERS.xl.bed);
const files = projectFiles(beds, { [part]: { pos: r.pos, idx: r.idx, mods: r.mods } }, PRINTERS.xl.bed, c, "test", {});
fs.writeFileSync(out + ".json", JSON.stringify(files)); console.log("wrote", out + ".json");
